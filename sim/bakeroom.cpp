// Bakes every purchasable room: day + night images with the window glass cut out, plus the glass spans.
// The little table (and its glass of water) is baked separately as a sprite: the room pictures are painted without
// it, and the sprite holds just the pixels the table changes (0xF81F = see-through), so the game can hide it.
// Usage: ./bakeroom ../src/game/roomdata.cpp
#include "roomstyles.h"
#include <stdio.h>
#include <vector>
using namespace cat;
int main(int argc, char** argv) {
  // game room id -> painter style id. Room 0 (the default home) is the Grimy Cartoon.
  // shop order = price order: Grimy (free), Treehouse, '70s, Modern, Villa, Log Cabin
  const int N = 7;
  const int STYLE[N] = {1, 4, 0, 2, 3, 5, 6};
  const int VIEW[N] = {0, 2, 0, 0, 1, 3, 4};   // what the window looks out on: 0 city, 1 sea, 2 forest, 3 river through the forest, 4 space
  static uint16_t buf[368 * 448]; Canvas hi(buf, 368, 448);
  static uint8_t mask[368 * 316];
  FILE* f = fopen(argv[1], "w");
  fprintf(f, "// GENERATED by sim/bakeroom.cpp - do not edit.\n#include \"roomdata.h\"\nnamespace cat {\n");
  const float hours[2] = {12.0f, 23.0f};
  const char* kind[2] = {"DAY", "NIGHT"};
  static int tb[16][4];   // each room's table sprite box: x, y, w, h (w 0 = no table)
  for (int r = 0; r < N; r++) {
    std::vector<std::vector<int>> spans;
    // the table sprite: paint the room with and without it (day and night) and keep what differs
    static uint16_t with[2][368 * 316], without[2][368 * 316];
    for (int k = 0; k < 2; k++) for (int t = 0; t < 2; t++) {
      for (int i = 0; i < 368 * 448; i++) buf[i] = 0;
      for (int i = 0; i < 368 * 316; i++) mask[i] = 0;
      gNoTable = t == 1;
      renderStyledRoomBaked(hi, STYLE[r], hours[k], mask);
      gNoTable = false;
      for (int i = 0; i < 368 * 316; i++) (t ? without : with)[k][i] = buf[52 * 368 + i];
    }
    int x0 = 368, y0 = 316, x1 = -1, y1 = -1;
    for (int y = 0; y < 316; y++) for (int x = 0; x < 368; x++) {
      const int i = y * 368 + x;
      if (with[0][i] != without[0][i] || with[1][i] != without[1][i]) { if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y; }
    }
    tb[r][0] = x1 < 0 ? 0 : x0; tb[r][1] = x1 < 0 ? 0 : y0; tb[r][2] = x1 < 0 ? 0 : x1 - x0 + 1; tb[r][3] = x1 < 0 ? 0 : y1 - y0 + 1;
    if (x1 >= 0) for (int k = 0; k < 2; k++) {
      fprintf(f, "static const uint16_t R%d_TBL_%s[%d * %d] = {\n", r, kind[k], tb[r][2], tb[r][3]);
      for (int y = y0; y <= y1; y++) {
        for (int x = x0; x <= x1; x++) {
          const int i = y * 368 + x;
          uint16_t v = 0xF81F;
          if (with[0][i] != without[0][i] || with[1][i] != without[1][i]) { v = with[k][i]; if (v == 0xF81F) v ^= 0x20; }
          fprintf(f, "%u,", v);
        }
        fprintf(f, "\n");
      }
      fprintf(f, "};\n");
    }
    for (int k = 0; k < 2; k++) {
      for (int i = 0; i < 368 * 448; i++) buf[i] = 0;
      for (int i = 0; i < 368 * 316; i++) mask[i] = 0;
      gNoTable = true;   // the room itself: no table
      renderStyledRoomBaked(hi, STYLE[r], hours[k], mask);
      gNoTable = false;
      fprintf(f, "static const uint16_t R%d_%s[ROOM_W * ROOM_H] = {\n", r, kind[k]);
      for (int y = 0; y < 316; y++) {
        for (int x = 0; x < 368; x++) fprintf(f, "%u,", buf[(y + 52) * 368 + x]);
        fprintf(f, "\n");
      }
      fprintf(f, "};\n");
      if (k == 0) {
        for (int y = 0; y < 316; y++) {
          int x = 0;
          while (x < 368) {
            if (!mask[y * 368 + x]) { x++; continue; }
            int x0 = x; while (x < 368 && mask[y * 368 + x]) x++;
            spans.push_back({y, x0, x - 1});
          }
        }
      }
    }
    fprintf(f, "static const GlassSpan R%d_GLASS[] = {\n", r);
    for (auto& s : spans) fprintf(f, "{%d,%d,%d},", s[0], s[1], s[2]);
    fprintf(f, "\n};\n");
    printf("room %d (style %d): %d glass spans\n", r, STYLE[r], (int)spans.size());
    fprintf(stderr, "%d\n", (int)spans.size());
    // remember count for the table
    static int counts[16]; counts[r] = (int)spans.size();
    if (r == N - 1) {
      fprintf(f, "const RoomImg ROOMS[NUM_ROOMS] = {\n");
      for (int q = 0; q < N; q++) {
        char td[24], tn[24];
        if (tb[q][2]) { snprintf(td, sizeof(td), "R%d_TBL_DAY", q); snprintf(tn, sizeof(tn), "R%d_TBL_NIGHT", q); }
        else { snprintf(td, sizeof(td), "nullptr"); snprintf(tn, sizeof(tn), "nullptr"); }
        fprintf(f, "  {R%d_DAY, R%d_NIGHT, R%d_GLASS, %d, %d, {%s, %s, %d, %d, %d, %d}},\n", q, q, q, counts[q], VIEW[q], td, tn, tb[q][0], tb[q][1], tb[q][2], tb[q][3]);
      }
      fprintf(f, "};\n");
    }
  }
  fprintf(f, "}  // namespace cat\n");
  fclose(f);
}
